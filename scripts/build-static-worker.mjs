import {cpSync,existsSync,mkdirSync,readFileSync,rmSync,writeFileSync} from "node:fs";
const root=process.cwd(),dist=`${root}/dist`;
if(existsSync(dist))rmSync(dist,{recursive:true,force:true});
mkdirSync(`${dist}/server`,{recursive:true});mkdirSync(`${dist}/client`,{recursive:true});mkdirSync(`${dist}/.openai`,{recursive:true});
cpSync(`${root}/public`,`${dist}/client`,{recursive:true});
cpSync(`${root}/worker/index.js`,`${dist}/server/index.js`);
cpSync(`${root}/.openai/hosting.json`,`${dist}/.openai/hosting.json`);
const index=readFileSync(`${dist}/client/index.html`,"utf8");
if(!index.includes("Spell Farm Academy"))throw new Error("Missing site index");
writeFileSync(`${dist}/server/wrangler.json`,JSON.stringify({main:"index.js",compatibility_date:"2026-05-15",assets:{directory:"../client",binding:"ASSETS"},d1_databases:[{binding:"DB",database_name:"site-creator-d1",database_id:"00000000-0000-4000-8000-000000000000"}],r2_buckets:[{binding:"BUCKET",bucket_name:"site-creator-r2"}]}));
console.log("Built static Worker with cloud storage routes");
